export function getRestaurantById(id: string): Restaurant | undefined {
  return restaurants.find((r) => r.id === id);
}

export function getReviewsByRestaurantId(restaurantId: string): Review[] {
  return reviews.filter((r) => r.restaurantId === restaurantId);
}

export function getTagsBySlugs(slugs: string[]): Tag[] {
  return tags.filter((t) => slugs.includes(t.slug));
}

export function getAverageRating(restaurantId: string): number {
  const restReviews = getReviewsByRestaurantId(restaurantId);
  if (restReviews.length === 0) return 0;
  const sum = restReviews.reduce((acc, r) => acc + r.rating, 0);
  return Math.round((sum / restReviews.length) * 10) / 10;
}

export function getDistrictsByCity(city: string): string[] {
  return [
    ...new Set(restaurants.filter((r) => r.city === city).map((r) => r.district)),
  ].sort();
}

